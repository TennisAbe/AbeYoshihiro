// Run against an isolated app/database: BASE_URL=http://127.0.0.1:18080 node src/test/browser/profile-favorite.cjs
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox']});
  try {
    const page = await browser.newPage();
    const base = process.env.BASE_URL || 'http://127.0.0.1:18080';
    const name = `Browser-${Date.now()}`;
    await page.goto(`${base}/characters/new`);
    assert.equal(await page.locator('#bust-field').isVisible(), false);
    await page.locator('#name').fill(name);
    await page.locator('#gender').selectOption('女');
    assert.equal(await page.locator('#bust-field').isVisible(), true);
    await page.locator('#heightCm').fill('165.5');
    await page.locator('#bustCm').fill('90');
    await page.getByRole('button', {name: '登録して編集を続ける'}).click();
    await page.waitForURL(/\/characters\/\d+\/edit$/);
    const editUrl = page.url();
    assert.equal(await page.locator('#heightCm').inputValue(), '165.5');
    assert.equal(await page.locator('#bustCm').inputValue(), '90');
    await page.goto(base);
    await page.getByRole('searchbox', {name:'キャラクター名'}).fill(name);
    await page.getByRole('button', {name:'検索',exact:true}).click();
    await page.waitForURL(/q=/);
    let navigations = 0;
    page.on('framenavigated', frame => { if(frame === page.mainFrame()) navigations++; });
    const star = page.locator('.favorite-button');
    await star.click();
    await page.waitForFunction(() => document.querySelector('.favorite-button').getAttribute('aria-pressed') === 'true');
    assert.equal(navigations, 0, 'favorite must not reload');
    await page.locator('.search input[name=favorites]').check();
    await page.getByRole('button', {name:'検索',exact:true}).click();
    await page.waitForURL(/favorites=true/);
    navigations = 0;
    await star.click();
    await page.waitForFunction(() => document.querySelector('.favorite-button').getAttribute('aria-pressed') === 'false');
    assert.equal(navigations,0);
    assert.equal(await page.locator('.character-card').count(),1,'keep current search results until next search');
    await page.getByRole('button',{name:'検索',exact:true}).click();
    await page.waitForSelector('.panel.empty');
    assert.equal(await page.locator('.character-card').count(),0);
    await page.goto(`${base}/?q=${name}`);
    await page.route('**/characters/*/favorite', route => route.fulfill({status:500,body:'error'}));
    await page.locator('.favorite-button').click();
    await page.getByRole('status').filter({hasText:'保存できませんでした'}).waitFor();
    assert.equal(await star.getAttribute('aria-pressed'),'false');
    assert.equal(await star.isDisabled(),false);
    await page.unroute('**/characters/*/favorite');
    await page.goto(editUrl);
    await page.locator('#gender').selectOption('男');
    assert.equal(await page.locator('#bust-field').isVisible(),false);
    await page.getByRole('button',{name:'変更を保存する'}).click();
    await page.waitForURL(/\/characters\/\d+$/);
    assert.equal(await page.locator('.dossier-content').getByText('胸囲',{exact:true}).count(),0);
    await page.goto(editUrl);
    await page.locator('#gender').selectOption('女');
    assert.equal(await page.locator('#bustCm').inputValue(),'');
    const created = await page.request.post(`${base}/characters`, {form: {name: `${name}-Friend`}, maxRedirects: 0});
    const targetId = created.headers().location.match(/characters\/(\d+)/)[1];
    const sourceId = editUrl.match(/characters\/(\d+)/)[1];
    const relation = await page.request.post(`${base}/characters/${sourceId}/relations`, {form:{targetId,relationType:'友人',description:'ブラウザーで検証した関係'},maxRedirects:0});
    assert.equal(relation.status(),302);
    await page.goto(`${base}/relationships`);
    const image = page.locator('.relationship-diagram img');
    await image.waitFor();
    await page.waitForFunction(() => document.querySelector('.relationship-diagram img').naturalWidth > 0);
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('link',{name:'相関図をダウンロード（SVG）'}).click();
    const download = await downloadEvent;
    assert.equal(download.suggestedFilename(),'noctalith-relationships.svg');
    assert.equal(await download.failure(),null);
    await page.screenshot({path:process.env.SCREENSHOT_PATH || '/tmp/noctalith-relationships.png', fullPage:true});
    console.log('PASS: profile visibility and persistence, favorite without navigation, deferred filtering, failure recovery, SVG rendering/download');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
