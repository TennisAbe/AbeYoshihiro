package com.abeyoshihiro.character_manager;

import static org.junit.jupiter.api.Assertions.*;
import java.sql.DriverManager;
import org.junit.jupiter.api.Test;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.builder.SpringApplicationBuilder;

class ExistingDatabaseUpgradeTests {
    @Test void upgradesPreviousH2EnumWithoutLosingCharacters() throws Exception {
        String url="jdbc:h2:mem:existing-world-enum;DB_CLOSE_DELAY=-1";
        try(var connection=DriverManager.getConnection(url,"sa","");var sql=connection.createStatement()) {
            sql.execute("create table original_character (id bigint generated by default as identity primary key, name varchar(255), world enum('ALTER_PALACE','MODERN_WORLD','OTHER_WORLD'))");
            sql.execute("insert into original_character(name,world) values ('Existing palace character','ALTER_PALACE')");
        }
        try(var app=new SpringApplicationBuilder(CharacterManagerApplication.class).web(WebApplicationType.NONE)
                .run("--spring.datasource.url="+url,"--spring.datasource.username=sa","--spring.datasource.password=",
                     "--spring.jpa.hibernate.ddl-auto=update", "--noctalith.upload-directory="+System.getProperty("java.io.tmpdir")+"/noctalith-enum-upgrade-tests")) {
            var repository=app.getBean(CharacterRepository.class);
            var old=repository.findAll().get(0);assertEquals("Existing palace character",old.getName());assertEquals(CharacterWorld.ALTER_PALACE,old.getWorld());
            var hero=new OriginalCharacter();hero.setName("New protagonist");hero.setWorld(CharacterWorld.PROTAGONIST);repository.saveAndFlush(hero);
            assertEquals(2,repository.count());assertTrue(repository.findById(hero.getId()).orElseThrow().isProtagonist());
        }
    }
}
