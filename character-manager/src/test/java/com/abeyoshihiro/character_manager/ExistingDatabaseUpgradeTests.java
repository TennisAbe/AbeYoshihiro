package com.abeyoshihiro.character_manager;

import static org.junit.jupiter.api.Assertions.*;
import java.sql.DriverManager;
import java.net.URI;
import java.net.http.*;
import java.util.List;
import java.io.ByteArrayInputStream;
import org.junit.jupiter.api.Test;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.builder.SpringApplicationBuilder;

class ExistingDatabaseUpgradeTests {
    @Test void upgradesPreviousH2EnumsAndIndexedOrdersWithoutLosingCharacters() throws Exception {
        String url="jdbc:h2:mem:existing-world-enum;DB_CLOSE_DELAY=-1";
        try(var connection=DriverManager.getConnection(url,"sa","");var sql=connection.createStatement()) {
            sql.execute("create table original_character (id bigint generated by default as identity primary key, name varchar(255), affiliation varchar(120), world enum('ALTER_PALACE','MODERN_WORLD','OTHER_WORLD'))");
            sql.execute("insert into original_character(name,affiliation,world) values ('Existing knight','Knights','ALTER_PALACE'),('Existing priest','Church','ALTER_PALACE')");
            // The previous regression fixture omitted this second persistent world column.
            sql.execute("create table affiliation_order (id bigint generated by default as identity primary key, affiliation varchar(120) not null, position integer not null, world enum('ALTER_PALACE','MODERN_WORLD','OTHER_WORLD') not null, unique(world,affiliation))");
            sql.execute("insert into affiliation_order(affiliation,position,world) values ('Church',1,'ALTER_PALACE'),('Knights',2,'ALTER_PALACE')");
        }
        try(var app=new SpringApplicationBuilder(CharacterManagerApplication.class).web(WebApplicationType.SERVLET)
                .run("--server.port=0", "--spring.datasource.url="+url,"--spring.datasource.username=sa","--spring.datasource.password=",
                     "--spring.jpa.hibernate.ddl-auto=update", "--noctalith.upload-directory="+System.getProperty("java.io.tmpdir")+"/noctalith-enum-upgrade-tests")) {
            var repository=app.getBean(CharacterRepository.class);
            var old=repository.findAll().get(0);assertEquals("Existing knight",old.getName());assertEquals(CharacterWorld.ALTER_PALACE,old.getWorld());
            var hero=new OriginalCharacter();hero.setName("New protagonist");hero.setWorld(CharacterWorld.PROTAGONIST);repository.saveAndFlush(hero);
            assertEquals(3,repository.count());assertTrue(repository.findById(hero.getId()).orElseThrow().isProtagonist());
            var ordering=app.getBean(AffiliationOrderingService.class);
            // Reproduce the reported failing query via the full roster, including PROTAGONIST.
            assertEquals(List.of(hero.getId(),2L,1L),ordering.roster().stream().map(OriginalCharacter::getId).toList());
            assertEquals(List.of("Church","Knights"),ordering.current(CharacterWorld.ALTER_PALACE));
            assertTrue(ordering.current(CharacterWorld.PROTAGONIST).isEmpty());
            try(var connection=DriverManager.getConnection(url,"sa","");var sql=connection.createStatement();var columns=sql.executeQuery("select data_type from information_schema.columns where table_name in ('ORIGINAL_CHARACTER','AFFILIATION_ORDER') and column_name='WORLD'")) {
                int count=0;while(columns.next()){assertEquals("CHARACTER VARYING",columns.getString(1));count++;}assertEquals(2,count);
            }
            String base="http://127.0.0.1:"+app.getEnvironment().getProperty("local.server.port");
            var client=HttpClient.newHttpClient();
            for(String path:List.of("/","/relationships","/relationships/diagram.svg","/affiliations/order","/backup/download","/share/download")) {
                var response=client.send(HttpRequest.newBuilder(URI.create(base+path)).GET().build(),HttpResponse.BodyHandlers.ofByteArray());
                assertEquals(200,response.statusCode(),path);
            }
            var backup=app.getBean(BackupService.class);
            assertEquals(3,backup.restore(new ByteArrayInputStream(backup.exportArchive())));
            assertEquals(List.of("Church","Knights"),ordering.current(CharacterWorld.ALTER_PALACE));
            assertEquals(6,ordering.roster().size());
            assertEquals(2,app.getBean(AffiliationOrderRepository.class).count());
        }
    }
}
