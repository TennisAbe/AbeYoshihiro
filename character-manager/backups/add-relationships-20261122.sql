CREATE LOCAL TEMPORARY TABLE IMPORT_RESOLVED (
    REF VARCHAR(12) PRIMARY KEY,
    CHARACTER_ID BIGINT NOT NULL UNIQUE
);
-- The primary key rejects ambiguous matches.
INSERT INTO IMPORT_RESOLVED
SELECT candidate.REF, local_character.ID
FROM IMPORT_CHARACTER candidate
JOIN ORIGINAL_CHARACTER local_character
    ON local_character.NAME = candidate.NAME
    AND local_character.WORLD = candidate.WORLD
    AND COALESCE(local_character.AFFILIATION, '') = candidate.AFFILIATION;

-- Abort on a missing match before any application data is written.
CREATE LOCAL TEMPORARY TABLE IMPORT_VALIDATION (
    MATCHED INTEGER CHECK (MATCHED = 42)
);
INSERT INTO IMPORT_VALIDATION SELECT COUNT(*) FROM IMPORT_RESOLVED;

