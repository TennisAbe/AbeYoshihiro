INSERT INTO CHARACTER_RELATION (SOURCE_ID, TARGET_ID, RELATION_TYPE, DESCRIPTION)
SELECT source_character.CHARACTER_ID, target_character.CHARACTER_ID,
       candidate.RELATION_TYPE, candidate.DESCRIPTION
FROM IMPORT_RELATION candidate
JOIN IMPORT_RESOLVED source_character ON source_character.REF = candidate.SOURCE_REF
JOIN IMPORT_RESOLVED target_character ON target_character.REF = candidate.TARGET_REF
WHERE NOT EXISTS (
    SELECT 1 FROM CHARACTER_RELATION existing
    WHERE existing.SOURCE_ID = source_character.CHARACTER_ID
      AND existing.TARGET_ID = target_character.CHARACTER_ID
      AND existing.RELATION_TYPE = candidate.RELATION_TYPE
);
